import yaml
import jinja2

from pkg_resources import resource_string



def repetition_allowed(field):
    """Return True if an MMD/ACDD field has repetition allowed, otherwise False."""
    if field is not None and 'maxOccurs' in field.keys():
        rep = True if field['maxOccurs'] not in ['0', '1'] else False
    else:
        rep = True

    return rep



def required(field):
    """Return True if a field is required, otherwise False."""
    if field is not None and 'minOccurs' in field.keys():
        field_required = bool(int(field['minOccurs']))
    else:
        field_required = False

    return field_required



def set_attribute(mmd_field, val, convention, attributes, req='not_required'):
    """Populate an attribute list from a legacy mmd_elements.yaml entry."""
    if type(val) is not dict:
        raise ValueError('val input must be dict')
    if convention not in val.keys():
        return None
    if mmd_field.split('.')[0] == 'not_mmd':
        mmd_field = ''

    for attr in val[convention].keys():
        if req == 'required' and not required(val[convention][attr]):
            continue
        if req == 'not_required' and required(val[convention][attr]):
            continue
        comment, sep, default, descr = '', '', '', ''
        recommended = True
        if val[convention][attr] is not None:
            attr_data = val[convention][attr].copy()
            comment = attr_data.pop('comment', '')
            descr = attr_data.pop('description', '')
            recommended = attr_data.pop('recommended', True)
            sep = attr_data.pop('separator', '')
            default = attr_data.pop('default', '')
        else:
            attr_data = None
        attributes[convention][req].append({
            'mmd_field': mmd_field,
            'attribute': attr,
            'repetition_allowed': repetition_allowed(attr_data),
            'comment': comment,
            'description': descr,
            'recommended': recommended,
            'separator': sep,
            'default': default,
        })



def set_attributes(mmd_field, val_dict, attributes):
    """Recursively populate legacy attribute structures from mmd_elements.yaml."""
    if type(val_dict) is not dict:
        return None
    set_attribute(mmd_field, val_dict, 'acdd', attributes, req='required')
    set_attribute(mmd_field, val_dict, 'acdd', attributes, req='not_required')
    set_attribute(mmd_field, val_dict, 'acdd_ext', attributes, req='required')
    set_attribute(mmd_field, val_dict, 'acdd_ext', attributes, req='not_required')
    subdict = val_dict.copy()
    subdict.pop('acdd', '')
    subdict.pop('acdd_ext', '')
    for key, val in subdict.items():
        mmd_field_name = mmd_field + '>' + key
        set_attributes(mmd_field_name, val, attributes)



def _load_yaml(filename):
    return yaml.load(
        resource_string(globals()['__name__'].split('.')[0], filename),
        Loader=yaml.FullLoader,
    )



def _bucket_for_requirement(entry):
    """Required if MMD requires it, else not_required."""
    return 'required' if entry.get('mmd_requirement_level') == 'Required' else 'not_required'



def _repetition_from_entry(entry):
    return bool(entry.get('separator'))



def _attribute_record(attribute, entry, mapping):
    return {
        'mmd_field': mapping.get(attribute) or '',
        'attribute': attribute,
        'repetition_allowed': _repetition_from_entry(entry),
        'comment': entry.get('help', entry.get('comment', '')),
        'description': entry.get('description', ''),
        'recommended': True,
        'separator': entry.get('separator', ''),
        'default': entry.get('default', ''),
    }



def nc_attrs_from_yaml():
    """Create an asciidoc document describing ACDD, MET extensions, and CF metadata."""
    mapping_yaml = _load_yaml('mapping.yaml')
    acdd_yaml = _load_yaml('acdd_elements.yaml')
    cf_yaml = _load_yaml('cf_elements.yaml')

    attributes = {
        'message': (
            'This file is autogenerated from https://github.com/metno/py-mmd-tools/'
            'blob/master/py_mmd_tools/yaml_to_adoc.py, '
            'https://github.com/metno/py-mmd-tools/blob/master/py_mmd_tools/'
            'mapping.yaml, https://github.com/metno/py-mmd-tools/blob/master/'
            'py_mmd_tools/acdd_elements.yaml, https://github.com/metno/py-mmd-tools/'
            'blob/master/py_mmd_tools/cf_elements.yaml, and '
            'https://github.com/metno/py-mmd-tools/blob/master/py_mmd_tools/'
            'templates/nc_attributes_template.adoc.\n\n'
            'Please do not update this file manually. Update the YAML source files '
            'instead.\n'
        ),
        'acdd': {'required': [], 'not_required': []},
        'acdd_ext': {'required': [], 'not_required': []},
        'cf': [],
    }

    for attribute, entry in acdd_yaml.items():
        group = 'acdd_ext' if entry.get('acdd_ext') else 'acdd'
        bucket = _bucket_for_requirement(entry)
        attributes[group][bucket].append(_attribute_record(attribute, entry, mapping_yaml))

    for attribute, entry in cf_yaml.items():
        attributes['cf'].append({
            'attribute': attribute,
            'mmd_field': mapping_yaml.get(attribute) or '',
            'required': entry['requirement_level'],
            'description': entry['description'],
        })

    env = jinja2.Environment(
        loader=jinja2.PackageLoader(globals()['__name__'].split('.')[0], 'templates'),
        autoescape=jinja2.select_autoescape(['html', 'xml']),
        trim_blocks=True,
        lstrip_blocks=True,
    )
    template = env.get_template('nc_attributes_template.adoc')
    return template.render(data=attributes)
